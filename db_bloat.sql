/* ==========================================================================
   db_bloat.sql

   Purpose
   -------
   Build a lab database whose tables carry a controlled, NON-uniform amount
   of bloat, to practice monitoring and cleanup (VACUUM, REINDEX,
   pg_repack...).

   How it works
   ------------
   1. sp_create_populated_tables : creates N tables and loads M rows in
                                   each.
   2. sp_generate_bloat          : disables autovacuum on those tables and
                                   runs random UPDATEs, so every table ends
                                   up with a different share of dead tuples
                                   (default range: 5% to 45%).
   3. bloat_plan                 : records the target of each table, so the
                                   result can be compared with what
                                   pgstattuple actually measures.

   Requirements
   ------------
   - PostgreSQL 11+ (procedures with COMMIT inside).
   - Extension pgstattuple, only for the verification step.
   - Free disk space: ~150 MB per 1M-row table (data + 3 indexes), plus the
     space and WAL generated by the UPDATEs.

   WARNING: lab use only. Never run this against a production database.
   ======================================================================== */


/* --------------------------------------------------------------------------
   Step 0: database
   ------------------------------------------------------------------------ */
CREATE DATABASE db_bloat;

\c db_bloat


/* --------------------------------------------------------------------------
   Step 1: plan table

   One row per target table. Filled by sp_generate_bloat.
     target_ratio : wanted share of dead tuples (0.05 = 5%)
     update_ratio : fraction of rows to UPDATE to reach that target
                    (update_ratio = target_ratio / (1 - target_ratio))
     rows_updated : rows really touched by the UPDATE
     finished_at  : when the UPDATE of that table finished
   ------------------------------------------------------------------------ */
DROP TABLE IF EXISTS bloat_plan;

CREATE TABLE bloat_plan (
    table_name   text PRIMARY KEY,
    target_ratio numeric(6,4) NOT NULL,
    update_ratio numeric(6,4) NOT NULL,
    rows_updated bigint,
    finished_at  timestamptz
);


/* --------------------------------------------------------------------------
   Step 2: sp_create_populated_tables

   Creates p_tables tables named <p_table_base_name><NNN>
   (e.g. tb_bloat_001) and loads p_rows rows into each one.

   Parameters
     p_tables          : how many tables to create        (default 100)
     p_rows            : rows loaded into each table      (default 1000000)
     p_table_base_name : table name prefix
                         (default 'tb_bloat_')

   Notes
     - Existing tables with the same names are DROPPED and recreated.
     - Each table is committed on its own, so a failure in the middle keeps
       the tables already finished and no huge transaction is held open.
       For this reason, CALL it outside an explicit BEGIN block.
   ------------------------------------------------------------------------ */
CREATE OR REPLACE PROCEDURE sp_create_populated_tables(
    p_tables          integer DEFAULT 100,
    p_rows            integer DEFAULT 1000000,
    p_table_base_name text    DEFAULT 'tb_bloat_'
)
AS $body$
DECLARE
    v_table text;   -- name of the table being created
BEGIN
    FOR i IN 1..p_tables LOOP
        -- Zero-padded sequence: tb_bloat_001, tb_bloat_002, ...
        v_table := format('%s%s', p_table_base_name, lpad(i::text, 3, '0'));

        EXECUTE format('DROP TABLE IF EXISTS %I', v_table);

        -- Table with a mix of types: numeric, text, timestamp and a payload
        -- column that makes each row wide enough for bloat to be visible.
        EXECUTE format($sql$
            CREATE TABLE %I (
                id          bigint        NOT NULL,
                customer_id integer       NOT NULL,
                amount      numeric(10,2) NOT NULL,
                status      text          NOT NULL,
                created_at  timestamptz   NOT NULL,
                payload     text          NOT NULL
            )$sql$, v_table);

        -- Load data first, build indexes afterwards (much faster than
        -- maintaining the indexes row by row during the INSERT).
        EXECUTE format($sql$
            INSERT INTO %I
            SELECT g,                                           -- id
                   (random() * 100000)::int,                    -- customer_id
                   round((random() * 1000)::numeric, 2),        -- amount
                   (ARRAY['new', 'paid', 'shipped', 'cancelled'])
                       [1 + (random() * 3)::int],               -- status
                   now() - random() * interval '2 years',       -- created_at
                   md5(g::text)                                 -- payload
            FROM generate_series(1, %s) AS g$sql$, v_table, p_rows);

        -- Three indexes. created_at is the column UPDATEd later, so its
        -- index (and the other two) will bloat along with the table.
        EXECUTE format('ALTER TABLE %I ADD PRIMARY KEY (id)', v_table);
        EXECUTE format('CREATE INDEX %I ON %I (customer_id)',
                       v_table || '_customer_id_idx', v_table);
        EXECUTE format('CREATE INDEX %I ON %I (created_at)',
                       v_table || '_created_at_idx', v_table);

        COMMIT;   -- one commit per table
        RAISE NOTICE 'Created % with % rows (% of %)',
                     v_table, p_rows, i, p_tables;
    END LOOP;
END;
$body$
LANGUAGE plpgsql;


/* Example ==================================================================
-- 100 tables x 1M rows
CALL sp_create_populated_tables();
-- 100 tables x 3M rows
CALL sp_create_populated_tables(100, 3000000);
-- quick smoke test
CALL sp_create_populated_tables(3, 1000);
-- custom prefix
CALL sp_create_populated_tables(10, 500000, 'tb_test_');
ANALYZE;
========================================================================== */


/* --------------------------------------------------------------------------
   Step 3: sp_generate_bloat

   Finds every table in schema public whose name starts with
   p_table_base_name and gives each one a DIFFERENT dead-tuple target
   between p_min_ratio and p_max_ratio.

   Parameters
     p_min_ratio       : lower bound, decimal (0.05 = 5%)   (default 0.05)
     p_max_ratio       : upper bound, decimal (0.45 = 45%)  (default 0.45)
     p_table_base_name : table name prefix
                         (default 'tb_bloat_')

   Method
     - Tables are ordered by md5(table name) and the targets are spread
       linearly over [min, max]. All targets are distinct and the order is
       shuffled relative to the table names.
     - To get a dead-tuple share t, a fraction t / (1 - t) of the rows is
       updated: every updated row leaves one dead version behind.
       Example: 45% dead => update ~82% of the rows.
     - The UPDATE touches created_at (indexed), which prevents HOT updates,
       so the indexes bloat too.
     - Rows are picked with random(), evaluated once per row.
     - Autovacuum is disabled on every target table, otherwise it would
       clean the dead tuples right after they are created.

   Notes
     - Each call ADDS new bloat to what already exists. To restart from
       zero, recreate the tables with sp_create_populated_tables.
     - Avoid heavy SELECTs and VACUUM on these tables before measuring:
       page pruning may remove part of the dead tuples.
     - Each table is committed on its own: CALL it outside a BEGIN block.
   ------------------------------------------------------------------------ */
CREATE OR REPLACE PROCEDURE sp_generate_bloat(
    p_min_ratio       numeric DEFAULT 0.05,
    p_max_ratio       numeric DEFAULT 0.45,
    p_table_base_name text    DEFAULT 'tb_bloat_'
)
AS $body$
DECLARE
    v_pattern     text;      -- LIKE pattern built from the prefix
    v_table_count integer;   -- how many tables match the prefix
    v_rec         record;    -- current table (name + rank)
    v_target      numeric;   -- dead-tuple share wanted for this table
    v_update      numeric;   -- fraction of rows to update to reach it
    v_rows        bigint;    -- rows actually updated
BEGIN
    -- Validate the range: 0 < min <= max < 1
    IF p_min_ratio <= 0 OR p_max_ratio >= 1
       OR p_min_ratio > p_max_ratio THEN
        RAISE EXCEPTION
            'Invalid range: min=%, max=% (expected 0 < min <= max < 1)',
            p_min_ratio, p_max_ratio;
    END IF;

    -- Escape the LIKE wildcards so the prefix is matched literally
    -- (otherwise "_" would match any single character).
    v_pattern := replace(replace(p_table_base_name, '_', '\_'), '%', '\%')
                 || '%';

    SELECT count(*) INTO v_table_count
    FROM pg_tables
    WHERE schemaname = 'public' AND tablename LIKE v_pattern;

    IF v_table_count = 0 THEN
        RAISE EXCEPTION 'No tables found with prefix "%" in schema public',
                        p_table_base_name;
    END IF;

    FOR v_rec IN
        -- rank_pos: 0..N-1, shuffled by md5 so neighbouring tables
        -- do not get neighbouring targets.
        SELECT tablename,
               row_number() OVER (ORDER BY md5(tablename)) - 1 AS rank_pos
        FROM pg_tables
        WHERE schemaname = 'public' AND tablename LIKE v_pattern
        ORDER BY tablename
    LOOP
        -- Spread targets evenly over [min, max]
        IF v_table_count = 1 THEN
            v_target := p_min_ratio;   -- single table: avoid division by 0
        ELSE
            v_target := p_min_ratio
                      + (p_max_ratio - p_min_ratio) * v_rec.rank_pos
                        / (v_table_count - 1);
        END IF;
        v_update := v_target / (1 - v_target);

        -- Register (or refresh) the plan for this table
        INSERT INTO bloat_plan (table_name, target_ratio, update_ratio)
        VALUES (v_rec.tablename, round(v_target, 4), round(v_update, 4))
        ON CONFLICT (table_name) DO UPDATE
            SET target_ratio = EXCLUDED.target_ratio,
                update_ratio = EXCLUDED.update_ratio,
                rows_updated = NULL,
                finished_at  = NULL;

        -- Keep autovacuum away from the table
        EXECUTE format(
            'ALTER TABLE public.%I SET (autovacuum_enabled = false)',
            v_rec.tablename);

        -- Random UPDATE: each row is chosen with probability v_update
        EXECUTE format(
            'UPDATE public.%I SET created_at = created_at + '
            'interval ''1 second'' WHERE random() < %s',
            v_rec.tablename, v_update);
        GET DIAGNOSTICS v_rows = ROW_COUNT;

        -- Record the result
        UPDATE bloat_plan
        SET rows_updated = v_rows, finished_at = clock_timestamp()
        WHERE table_name = v_rec.tablename;

        COMMIT;   -- one commit per table
        RAISE NOTICE '%: target ratio %, % rows updated',
                     v_rec.tablename, round(v_target, 4), v_rows;
    END LOOP;
END;
$body$
LANGUAGE plpgsql;


/* Example ==================================================================

\timing on
CALL sp_generate_bloat();                        -- range 0.05 to 0.45
CALL sp_generate_bloat(0.10, 0.30);              -- custom range
CALL sp_generate_bloat(0.05, 0.45, 'tb_test_');  -- custom prefix

-- Verification: compare the target with what was really measured.
-- pgstattuple returns percentages as double precision, hence the cast
-- to numeric before round(). actual_dead_ratio is computed over table
-- bytes, so it usually lands a little below the target.

CREATE EXTENSION IF NOT EXISTS pgstattuple;

SELECT p.table_name,
       p.target_ratio,
       round((s.dead_tuple_percent / 100)::numeric, 4) AS actual_dead_ratio,
       round((s.free_percent / 100)::numeric, 4)       AS free_ratio,
       pg_size_pretty(s.table_len)                     AS table_size
FROM bloat_plan p
CROSS JOIN LATERAL
     pgstattuple(('public.' || quote_ident(p.table_name))::regclass) s
ORDER BY p.target_ratio;
*/
